import os

def op(ratio=1.0, ol=99, r=(99, 50, 35, 40), l=(99, 80, 0, 0), kvs=2, rs=1, det=7,
       bp=39, ld=0, rd=0, lc=0, rc=0, ams=0, fixed=False, fine=None):
    if fixed:
        fc, ff = int(ratio), int(fine or 0)
    else:
        if ratio < 1.0:
            fc, ff = 0, 0          # 0,5
        else:
            fc = int(ratio)
            ff = int(round((ratio / fc - 1.0) * 100)) if fine is None else fine
            ff = max(0, min(99, ff))
    return [*r, *l, bp, ld, rd, lc, rc, rs, ams, kvs, ol, 1 if fixed else 0, fc, ff, det]

OFF = op(ol=0)

def voice(name, alg, ops, fb=0, lfo=(35, 0, 0, 0, 1, 0, 3), pr=(99, 99, 99, 99), pl=(50, 50, 50, 50), oks=1, tr=24):
    ops = list(ops) + [OFF] * (6 - len(ops))
    data = []
    for o in reversed(ops):           # OP6 en premier
        data += o
    data += list(pr) + list(pl) + [alg - 1, fb, oks]
    spd, dly, pmd, amd, sync, wave, pms = lfo
    data += [spd, dly, pmd, amd, sync, wave, pms, tr]
    data += [ord(c) for c in name.ljust(10)[:10]]
    data += [0x3f]
    assert len(data) == 156, (name, len(data))
    return data

